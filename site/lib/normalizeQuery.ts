/**
 * 検索語の表記ゆれ（全角英数字・全角/和文のダッシュ・全角スペース）をそろえる。
 * スマホの日本語入力では品番が「ＳＳＩＳ－１２３」「SSIS－123」「SSIS ー123」のように入り、
 * 品番の点引きも英字コアの照合も外れて 0件 になっていた（2026-10-08 実測）。
 * 英数字にはさまれたダッシュ類だけを '-' にするので「ラーメン」の長音は変わらない。
 */
export function normalizeQuery(raw: string): string {
    return raw.normalize('NFKC')
        .replace(/([A-Za-z0-9])\s*[‐‑‒–—―ー－−]\s*([A-Za-z0-9])/g, '$1-$2')
        .replace(/\s+/g, ' ')
        .trim();
}
